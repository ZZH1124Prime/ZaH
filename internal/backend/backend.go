var ErrManual = errors.New("upstream operation requires user interaction")
var ErrUnsupported = errors.New("upstream operation is not supported automatically")
var idPattern = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{7,63}$`)
var digestPattern = regexp.MustCompile(`^[a-f0-9]{64}$`)

// Binding maps a pinned selected host directory beneath /mnt/zah.
type Binding struct {
	Host   host.BindingEvidence `json:"host"`
	Target string               `json:"target"`
}

// InstallRequest uses a verified archived material and a dedicated private HOME.
type InstallRequest struct {
	Material       *InstallMaterial     `json:"material,omitempty"`
	InstanceID     string               `json:"instance_id"`
	ArtifactPath   string               `json:"artifact_path"`
	ArtifactSHA256 string               `json:"artifact_sha256"`
	PrivateHome    string               `json:"private_home"`
	Recipe         recipe.Recipe        `json:"recipe"`
	Bindings       []Binding            `json:"bindings,omitempty"`
	Windows        *BottlesRegistration `json:"windows,omitempty"`
}

// Step describes an immutable operation. ResourceID must come from create evidence.
type Step struct {
	Kind       string         `json:"kind"`
	Request    InstallRequest `json:"request"`
	ResourceID string         `json:"resource_id,omitempty"`
	Mode       string         `json:"mode"`
	Reason     string         `json:"reason,omitempty"`
}

// Plan is a reviewable list of external effects and required manual work.
type Plan struct {
	Backend      string   `json:"backend"`
	RecipeDigest string   `json:"recipe_digest"`
	Steps        []Step   `json:"steps"`
	Warnings     []string `json:"warnings"`
}

// Evidence records normalized identities without leaking full upstream inspect data.
type Evidence struct {
	Lifecycle  *SupervisedCompletion `json:"lifecycle,omitempty"`
	ResourceID string                `json:"resource_id,omitempty"`
	State      string                `json:"state"`
	Entry      string                `json:"entry,omitempty"`
	Result     process.Result        `json:"result"`
	Windows    *BottlesRegistration  `json:"windows,omitempty"`
	Preflight  *InstallPreflight     `json:"preflight,omitempty"`
}

// RuntimeBackend is the management-facing contract; capability assessment
// precedes execution and manual operations return ErrManual, never fake success.
type RuntimeBackend interface {
	Probe(context.Context, string) (process.Result, error)
	Assess(InstallRequest) (Assessment, error)
	PlanInstall(InstallRequest) (Plan, error)
	ExecuteStep(context.Context, Step) (Evidence, error)
	Inspect(context.Context, InstallRequest, string) (Evidence, error)
	Launch(context.Context, InstallRequest, string) (Evidence, error)
	Stop(context.Context, InstallRequest, string) (Evidence, error)
	PlanRemove(InstallRequest, string) (Plan, error)
	DescribeSnapshot(InstallRequest) (map[string]string, error)
	ExportSnapshot(context.Context, InstallRequest, string) (Evidence, error)
	PlanRestore(InstallRequest) (Plan, error)
}

var _ RuntimeBackend = Adapter{}

// Adapter only executes operations generated by this package; it never accepts argv from RPC.
type Adapter struct{ Runner process.Runner }

func (a Adapter) runner() process.Runner {
	if a.Runner != nil {
		return a.Runner
	}
	return process.OSRunner{}
}
func name(id string) string { return "zah-" + id }

// Distrobox create 1.8.2.5 reparses generated arguments with eval. Reject
// characters that can change that second parse, while retaining spaces/Unicode.
func unsafePath(p string) bool { return strings.ContainsAny(p, "\x00\n\r\t:\"'`$\\;&|<>(){}[]*?!") }

func validate(r InstallRequest) error {
	if !idPattern.MatchString(r.InstanceID) || !digestPattern.MatchString(r.ArtifactSHA256) {
		return errors.New("invalid instance or material digest")
	}
	for _, p := range []string{r.ArtifactPath, r.PrivateHome} {
		if !filepath.IsAbs(p) || filepath.Clean(p) != p || p == "/" || unsafePath(p) {
			return errors.New("invalid absolute backend path")
		}
	}
	if len(r.Bindings) > 64 {
		return errors.New("too many file bindings")
	}
	seen := map[string]bool{}
	for _, b := range r.Bindings {
		validTarget := strings.HasPrefix(b.Target, "/mnt/zah/") && filepath.Clean(b.Target) == b.Target && !unsafePath(b.Target)
		if r.Recipe.Platform == "windows" {
			validTarget = validWindowsDrive(b.Target)
		}
		if !filepath.IsAbs(b.Host.Path) || filepath.Clean(b.Host.Path) != b.Host.Path || unsafePath(b.Host.Path) || !validTarget || seen[b.Target] {
			return errors.New("invalid or duplicate file binding")
		}
		seen[b.Target] = true
	}
	return r.Recipe.Validate()
}

// PlanInstall has no side effects and never probes the daemon.
func (a Adapter) PlanInstall(r InstallRequest) (Plan, error) {
	if err := validate(r); err != nil {
		return Plan{}, err
	}
	p := Plan{RecipeDigest: r.Recipe.Digest(), Warnings: []string{"Unverified application compatibility; installer success is not capability validation."}}
	add := func(k, mode, why string) {
		p.Steps = append(p.Steps, Step{Kind: k, Request: r, Mode: mode, Reason: why})
	}
	if r.Recipe.Platform == "linux" {
		p.Backend = "distrobox-docker"
		p.Warnings = append(p.Warnings, "Distrobox integrates host services and is not a security sandbox; no privilege escalation is automated.", "Before any write, require a local digest-pinned linux/amd64 image and inspect actual material/HOME/Docker filesystems; estimates are not a disk quota. Unknown storage requires manual preparation.")
		if r.Recipe.Strategy == "deb" {
			p.Warnings = append(p.Warnings, "Deb installation opens the native graphical package installer inside the verified managed container; the user chooses whether to install. Container tool dependencies are prepared separately; no host elevation fallback.")
		}
		add("prepare_material", "automatic", "")
		add("create", "automatic", "")
		add("install", "automatic", "")
		add("verify_entry", "automatic", "")
	} else {
		p.Backend = "bottles-flatpak"
		if r.Material != nil {
			if e := validateInstallMaterial(r); e != nil {
				return Plan{}, e
			}
			p.Warnings = append(p.Warnings, "Create a new dedicated Bottle using the selected locally installed runner; upstream may download official application environment dependencies.", "Only this new Bottle is configured with winebridge=false and sandbox=false for verified prefix control. No host/Flatpak permissions are changed.", "Copy the complete portable ZIP tree or single EXE into the new Bottle; do not execute the application installer yet. Native GUI installation and final entry selection are separate steps.")
			add("prepare_bottle", "automatic", "Create dedicated Bottle, archive copy and verify exact Run/Stop entry")
			return p, nil
		}
		p.Warnings = append(p.Warnings, "Flatpak file permissions affect Bottles, not only one bottle.", "Configure selected D:..Y: drives in Winecfg and exact Flatpak directory access manually; registration and every launch recheck current mapping/permission evidence. Existing sandboxes are not proof of refreshed permissions.")
		add("create", "manual", "Create a dedicated bottle using the exact runner, then verify its identity in Bottles.")
		add("install", "manual", "Grant access only to the archived installer and install interactively; MSI requires its own installer workflow.")
		add("verify_entry", "manual", "Register the installed program in Bottles and verify its path; CLI listing alone is insufficient.")
	}
	return p, nil
}
func command(program string, args ...string) process.Command {
	return process.Command{Program: program, Args: args, Timeout: 30 * time.Second, MaxOutput: 1 << 20, SafeCancel: true}
}
func dbx(args ...string) process.Command {
	c := command("distrobox", args...)
	c.Env = map[string]string{"DBX_CONTAINER_MANAGER": "docker", "DBX_NON_INTERACTIVE": "1", "SHELL": "/bin/sh"}
	return c
}
func enter(r InstallRequest, args ...string) process.Command {
	base := []string{"enter", "--name", name(r.InstanceID), "--no-tty", "--no-workdir", "--"}
	c := dbx(append(base, args...)...)
	// Enter may start a stopped container and perform first-run package/user
	// initialization, even when the eventual command is only id or test.
	// Do not kill that transaction on a probe timeout or release its locks early.
	c.SafeCancel = false
	c.Timeout = 0
	return c
}

// Probe explicitly runs version/package inspection; it is not the passive host doctor.
func (a Adapter) Probe(ctx context.Context, platform string) (process.Result, error) {
	if platform == "linux" {
		return a.runner().Run(ctx, command("distrobox", "--version"))
	}
	if platform == "windows" {
		return a.runner().Run(ctx, command("flatpak", "info", "com.usebottles.bottles"))
	}
	return process.Result{}, ErrUnsupported
}

// Inspect checks Docker resource identity and ZaH's creation label.
func (a Adapter) Inspect(ctx context.Context, r InstallRequest, resourceID string) (Evidence, error) {
	if err := validate(r); err != nil {
		return Evidence{}, err
	}
	if r.Recipe.Platform == "windows" {
		return a.InspectBottles(ctx, r, resourceID)
	}
	if !digestPattern.MatchString(resourceID) {
		return Evidence{}, errors.New("full Docker resource ID required")
	}
	res, err := a.runner().Run(ctx, command("docker", "container", "inspect", resourceID))
	if err != nil {
		return Evidence{State: "unknown", Result: res}, err
	}
	if res.Truncated {
		return Evidence{}, errors.New("inspect output exceeds limit")
	}
	var rows []struct {
		ID     string `json:"Id"`
		Name   string
		Config struct{ Labels map[string]string }
		State  struct{ Running bool }
	}
	if err = json.Unmarshal([]byte(res.Stdout), &rows); err != nil || len(rows) != 1 {
		return Evidence{}, errors.New("invalid Docker inspect response")
	}
	row := rows[0]
	if row.ID != resourceID || row.Name != "/"+name(r.InstanceID) || row.Config.Labels["org.zah.instance"] != r.InstanceID {
		return Evidence{State: "changed"}, errors.New("resource identity or ownership changed")
	}
	state := "stopped"
	if row.State.Running {
		state = "running"
	}
	return Evidence{ResourceID: row.ID, State: state}, nil
}

// ExecuteStep revalidates inputs and never retries a side effect automatically.
func (a Adapter) ExecuteStep(ctx context.Context, s Step) (Evidence, error) {
	r := s.Request
	if a.Runner == nil && os.Geteuid() == 0 {
		return Evidence{}, errors.New("backend applications must run as an ordinary user")
	}
	if err := validate(r); err != nil {
		return Evidence{}, err
	}
	if s.Mode != "automatic" {
		return Evidence{State: "waiting_user"}, ErrManual
	}
	if r.Recipe.Platform == "windows" {
		if s.Kind == "remove" {
			return a.removeBottles(ctx, r, s.ResourceID)
		}
		if s.Kind == "prepare_bottle" {
			return a.prepareBottles(ctx, r)
		}
		if s.Kind == "launch" {
			return a.launchBottles(ctx, r, s.ResourceID)
		}
		return Evidence{State: "waiting_user"}, ErrManual
	}
	for _, b := range r.Bindings {
		if err := host.VerifyBinding(b.Host); err != nil {
			return Evidence{}, err
		}
	}
	if s.Kind == "prepare_material" {
		if _, err := localInstallCapacity(r); err != nil {
			return Evidence{}, fmt.Errorf("%w: %v", ErrManual, err)
		}
		return prepare(ctx, r)
	}
	if s.Kind == "create" {
		proof, err := a.PreflightInstall(ctx, r)
		if err != nil {
			return Evidence{Preflight: &proof}, err
		}
		c := command("docker", "container", "ls", "--all", "--filter", "name=^/"+name(r.InstanceID)+"$", "--format", "{{.ID}}")
		out, err := a.runner().Run(ctx, c)
		if err != nil {
			return Evidence{State: "unknown"}, err
		}
		if strings.TrimSpace(out.Stdout) != "" {
			return Evidence{}, errors.New("container name already exists; do not adopt or overwrite")
		}
		flags := "--label org.zah.instance=" + r.InstanceID
		// --volume itself splits on spaces in the reviewed Distrobox version.
		// Build the reviewed additional-flags grammar, quoting validated paths.
		for _, b := range r.Bindings {
			mode := "rw"
			if b.Host.ReadOnly {
				mode = "ro"
			}
			flags += " --volume \"" + b.Host.Path + ":" + b.Target + ":" + mode + "\""
		}
		args := []string{"create", "--yes", "--name", name(r.InstanceID), "--image", r.Recipe.Image, "--home", r.PrivateHome, "--no-entry", "--additional-flags", flags}
		if len(r.Recipe.Dependencies) > 0 {
			args = append(args, "--additional-packages", strings.Join(r.Recipe.Dependencies, " "))
		}
		c = dbx(args...)
		c.SafeCancel = false
		c.Timeout = 0
		res, err := a.runner().Run(ctx, c)
		if err != nil {
			return Evidence{State: "unknown", Result: res}, err
		}
		c = command("docker", "container", "inspect", "--format", "{{.Id}}", name(r.InstanceID))
		out, err = a.runner().Run(ctx, c)
		if err != nil {
			return Evidence{State: "unknown", Result: res}, err
		}
		id := strings.TrimSpace(out.Stdout)
		evidence, err := a.Inspect(ctx, r, id)
		evidence.Result = res
		return evidence, err
	}
	evidence, err := a.Inspect(ctx, r, s.ResourceID)
	if err != nil {
		return evidence, err
	}
	var c process.Command
	switch s.Kind {
	case "install":
		proof, err := a.PreflightInstall(ctx, r)
		if err != nil {
			return Evidence{Preflight: &proof}, err
		}
		if err = a.verifyInstallImage(ctx, r, s.ResourceID, *proof.Image); err != nil {
			return Evidence{State: "changed", Preflight: &proof}, err
		}
		if err = a.verifyRuntimeBindings(ctx, r, s.ResourceID); err != nil {
			return Evidence{State: "changed", Preflight: &proof}, err
		}
		evidence.Preflight = &proof
		material := filepath.Join(r.PrivateHome, ".zah-install", "installer."+r.Recipe.Strategy)
		if err = verifyFile(ctx, material, r.ArtifactSHA256); err != nil {
			return Evidence{}, err
		}
		if r.Recipe.Strategy == "appimage" {
			c = enter(r, "env", "-C", filepath.Dir(material), material, "--appimage-extract")
		} else {
			// First enter initializes Distrobox and the declared GUI dependencies.
			// The target package is only installed through the user's native GUI.
			if _, err = a.runner().Run(ctx, enter(r, "/usr/bin/true")); err != nil {
				return Evidence{State: "unknown"}, err
			}
			return a.LaunchLinuxInstallationGUI(ctx, r, s.ResourceID, "install")
		}
		c.SafeCancel = false
		c.Timeout = 0
	case "verify_entry":
		if err = a.verifyRuntimeBindings(ctx, r, s.ResourceID); err != nil {
			return Evidence{State: "changed"}, err
		}
		if r.Recipe.PendingEntry {
			evidence.State = "environment_prepared"
			return evidence, nil
		}
		if r.Recipe.LinuxEntry != nil {
			if _, e := a.selectedLinuxCommand(ctx, r, s.ResourceID); e != nil {
				return Evidence{}, e
			}
			evidence.State = "entry_verified"
			evidence.Entry = entry(r)
			return evidence, nil
		}
		c = enter(r, "test", "-x", entry(r))
	case "launch":
		if err = a.verifyRuntimeBindings(ctx, r, s.ResourceID); err != nil {
			return Evidence{State: "changed"}, err
		}
		argv, e := a.selectedLinuxCommand(ctx, r, s.ResourceID)
		if e != nil {
			return Evidence{}, e
		}
		c = enter(r, argv...)
		c.Timeout = 0
		c.SafeCancel = false
	case "remove":
		if evidence.State != "stopped" {
			return evidence, errors.New("stop all writers before removing the environment")
		}
		c = command("docker", "container", "rm", s.ResourceID)
		c.SafeCancel = false
		c.Timeout = 0
	default:
		return Evidence{}, ErrUnsupported
	}
	res, err := a.runner().Run(ctx, c)
	evidence.Result = res
	if err != nil {
		evidence.State = "unknown"
		return evidence, err
	}
	switch s.Kind {
	case "verify_entry":
		evidence.State = "entry_verified"
		evidence.Entry = entry(r)
	case "install":
		evidence.State = "installed_unverified"
	case "launch":
		evidence.State = "launcher_exited_application_unknown"
	case "remove":
		evidence.State = "removed"
	}
	return evidence, nil
}
func entry(r InstallRequest) string {
	if selected := r.Recipe.LinuxEntry; selected != nil {
		if selected.HomeRelative {
			return filepath.Join(r.PrivateHome, filepath.FromSlash(selected.Path))
		}
		return selected.Path
	}
	if r.Recipe.Strategy == "appimage" {
		return filepath.Join(r.PrivateHome, ".zah-install", r.Recipe.Entry)
	}
	return r.Recipe.Entry
}
func verifyFile(ctx context.Context, p, digest string) error {
	st, err := os.Lstat(p)
	if err != nil {
		return err
	}
	if !st.Mode().IsRegular() {
		return errors.New("material must be a regular file")
	}
	f, err := os.Open(p)
	if err != nil {
		return err
	}
	defer f.Close()
	h := sha256.New()
	buf := make([]byte, 128<<10)
	for {
		if err = ctx.Err(); err != nil {
			return err
		}
		n, e := f.Read(buf)
		if n > 0 {
			h.Write(buf[:n])
		}
		if e == io.EOF {
			break
		}
		if e != nil {
			return e
		}
	}
	if hex.EncodeToString(h.Sum(nil)) != digest {
		return errors.New("material digest changed")
	}
	return nil
}
func prepare(ctx context.Context, r InstallRequest) (Evidence, error) {
	if err := verifyFile(ctx, r.ArtifactPath, r.ArtifactSHA256); err != nil {
		return Evidence{}, err
	}
	// Reject symlink ancestors: installation may write executable code below HOME.
	for p := r.PrivateHome; p != "/"; p = filepath.Dir(p) {
		s, e := os.Lstat(p)
		if os.IsNotExist(e) {
			continue
		}
		if e != nil {
			return Evidence{}, e
		}
		if s.Mode()&os.ModeSymlink != 0 || !s.IsDir() {
			return Evidence{}, errors.New("private HOME traverses a non-directory or symlink")
		}
	}
	dir := filepath.Join(r.PrivateHome, ".zah-install")
	if err := os.MkdirAll(dir, 0700); err != nil {
		return Evidence{}, err
	}
	st, err := os.Lstat(dir)
	if err != nil || !st.IsDir() || st.Mode()&os.ModeSymlink != 0 {
		return Evidence{}, errors.New("unsafe installation directory")
	}
	dest := filepath.Join(dir, "installer."+r.Recipe.Strategy)
	f, err := os.OpenFile(dest, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0700)
	if err != nil {
		return Evidence{}, err
	}
	ok := false
	defer func() {
		f.Close()
		if !ok {
			os.Remove(dest)
		}
	}()
	src, err := os.Open(r.ArtifactPath)
	if err != nil {
		return Evidence{}, err
	}
	defer src.Close()
	if _, err = io.Copy(f, contextReader{ctx, src}); err != nil {
		return Evidence{}, err
	}
	if err = f.Sync(); err != nil {
		return Evidence{}, err
	}
	if err = f.Close(); err != nil {
		return Evidence{}, err
	}
	if err = verifyFile(ctx, dest, r.ArtifactSHA256); err != nil {
		return Evidence{}, err
	}
	ok = true
	return Evidence{State: "material_prepared"}, nil
}

// Stop is an explicit whole-environment operation. Each managed environment is
// dedicated to one application version; callers must review this scope.
func (a Adapter) Stop(ctx context.Context, r InstallRequest, resourceID string) (Evidence, error) {
	return a.stopEnvironment(ctx, r, resourceID)
}

// PlanRemove preserves private data and materials and requires owned resource identity.
func (a Adapter) PlanRemove(r InstallRequest, resourceID string) (Plan, error) {
	if err := validate(r); err != nil {
		return Plan{}, err
	}
	if !digestPattern.MatchString(resourceID) {
		return Plan{}, errors.New("resource identity required")
	}
	mode := "automatic"
	if r.Recipe.Platform != "linux" && (r.Windows == nil || r.Windows.Control == nil) {
		mode = "manual"
	}
	return Plan{Backend: r.Recipe.Platform, RecipeDigest: r.Recipe.Digest(), Steps: []Step{{Kind: "remove", Request: r, ResourceID: resourceID, Mode: mode}}, Warnings: []string{"Linux private HOME, host shared files and archived installers are preserved. Windows removal permanently deletes only the exact dedicated Bottle prefix after stopped-state verification."}}, nil
}

// DescribeSnapshot exposes an honest capability: restoration needs a verified upstream contract.
func (a Adapter) DescribeSnapshot(r InstallRequest) (map[string]string, error) {
	if err := validate(r); err != nil {
		return nil, err
	}
	return map[string]string{"mode": "manual", "consistency": "cold", "restore": "unverified", "reason": "Full environment restore requires target-machine identity, mounts, runner and upstream validation."}, nil
}

// Assessment distinguishes supported automation from interactive prerequisites.
type Assessment struct {
	Backend     string   `json:"backend"`
	Install     string   `json:"install"`
	Launch      string   `json:"launch"`
	Stop        string   `json:"stop"`
	Snapshot    string   `json:"snapshot"`
	Restore     string   `json:"restore"`
	Limitations []string `json:"limitations"`
}

// Assess never equates an available executable with a working runtime.
func (a Adapter) Assess(r InstallRequest) (Assessment, error) {
	if err := validate(r); err != nil {
		return Assessment{}, err
	}
	v := Assessment{Backend: r.Recipe.Platform, Install: "manual", Launch: "manual", Stop: "unsupported", Snapshot: "manual", Restore: "manual", Limitations: []string{"Runtime versions and application capabilities require explicit real-machine verification.", "No root helper, daemon reconfiguration, host network change or global cleanup is implemented."}}
	if r.Recipe.Platform == "linux" {
		v.Install = "automatic_after_approval"
		v.Stop = "automatic_owned_environment_after_approval"
		v.Launch = "automatic_for_verified_entry"
	}
	if r.Recipe.Platform == "windows" && r.Windows != nil {
		if r.Windows.Control != nil {
			v.Stop = "automatic_exact_wine_prefix_after_approval"
		}
		v.Launch = "automatic_for_verified_entry"
	}
	return v, nil
}

// Programs retrieves supported Bottles CLI evidence. It does not claim that the
// upstream list includes manually installed programs or verify their paths.
func (a Adapter) Programs(ctx context.Context, instanceID string) (process.Result, error) {
	if !idPattern.MatchString(instanceID) {
		return process.Result{}, errors.New("invalid instance ID")
	}
	c := command("flatpak", "run", "--command=bottles-cli", "com.usebottles.bottles", "--json", "programs", "-b", name(instanceID))
	return a.runner().Run(ctx, c)
}

// Launch waits for the registered entry. The worker owns its lifetime; closing
// the manager connection is not an application stop operation.
func (a Adapter) Launch(ctx context.Context, r InstallRequest, resourceID string) (Evidence, error) {
	return a.ExecuteStep(ctx, Step{Kind: "launch", Request: r, ResourceID: resourceID, Mode: "automatic"})
}

// ExportSnapshot deliberately does not substitute a configuration export for a
// full environment backup. Cold, validated upstream export is a manual boundary.
func (a Adapter) ExportSnapshot(context.Context, InstallRequest, string) (Evidence, error) {
	return Evidence{State: "waiting_user"}, ErrManual
}

// PlanRestore never replays an archived inspect structure or archived command.
func (a Adapter) PlanRestore(r InstallRequest) (Plan, error) {
	if err := validate(r); err != nil {
		return Plan{}, err
	}
	return Plan{Backend: r.Recipe.Platform, RecipeDigest: r.Recipe.Digest(), Steps: []Step{{Kind: "restore", Request: r, Mode: "manual", Reason: "Restore using supported upstream tools, rebind target user/HOME and verify the complete environment before registering ready."}}, Warnings: []string{"Cross-machine restoration is not verified for this combination."}}, nil
}

// contextReader checks cancellation between local copy chunks.
type contextReader struct {
	ctx context.Context
	r   io.Reader
}

func (r contextReader) Read(p []byte) (int, error) {
	if err := r.ctx.Err(); err != nil {
		return 0, err
	}
	return r.r.Read(p)
}
